"""Generate the display-cell widths GCC gives characters in diagnostics.

Writes src/diagnostics/cell_width.rs from the Unicode Character Database
files UnicodeData.txt, EastAsianWidth.txt and PropList.txt, which must be in
the directory given. GCC 14 builds its `cpp_wcwidth` table (libcpp's
generated_cpp_wcwidth.h) from Unicode 15.1 with glibc's `utf8_gen.py` rules,
which this script follows, so fetch that version and commit the result:

    curl -O https://www.unicode.org/Public/15.1.0/ucd/{UnicodeData,EastAsianWidth,PropList}.txt
    python3 -I scripts/generate_cell_widths.py <directory>

`--check` exits 1 instead of writing when the file would change.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/diagnostics/cell_width.rs"
UNICODE_VERSION = "15.1.0"


def code_points(field):
    first, _, last = field.strip().partition("..")
    return range(int(first, 16), int(last or first, 16) + 1)


def widths(ucd):
    """Each code point's width under GCC 14's contrib/unicode/from_glibc/
    utf8_gen.py `process_width` and gen_wcwidth.py."""
    assigned = set()
    marks = []
    first = None
    for line in open(ucd / "UnicodeData.txt", encoding="utf-8"):
        fields = line.split(";")
        code = int(fields[0], 16)
        if fields[4] == "NSM" or fields[2] in ("Cf", "Me", "Mn"):
            marks.append(code)
        if fields[1].endswith(", First>"):
            first = code
        elif fields[1].endswith(", Last>"):
            assigned.update(range(first, code + 1))
        else:
            assigned.add(code)
    width = {}
    for line in open(ucd / "EastAsianWidth.txt", encoding="utf-8"):
        # Reserved ranges are left at the default width.
        if re.match(r".*<reserved-.+>\.\.<reserved-.+>.*", line):
            continue
        if re.match(r"^[^;]*;\s*[WF]\s*", line):
            for code in code_points(line.split(";")[0]):
                width[code] = 2
    for code in marks:
        width[code] = 0
    for line in open(ucd / "PropList.txt", encoding="utf-8"):
        if re.match(r"^[^;]*;[\s]*Prepended_Concatenation_Mark", line):
            for code in code_points(line.split(";")[0]):
                del width[code]
    width.pop(0xAD, None)
    for code in [*range(0x1160, 0x1200), *range(0xD7B0, 0xD800)]:
        if code in assigned:
            width[code] = 0
    for code in [*range(0x3248, 0x3250), *range(0x4DC0, 0x4E00)]:
        width[code] = 2
    table = [1] * 0x110000
    for code, value in width.items():
        table[code] = value
    table[0:255] = [1] * 255
    return table


def runs(table):
    """The last code point and width of each run, as gen_wcwidth.py writes
    them: the final run, which ends at U+10FFFF, is left to the default."""
    found = []
    current = [-1, 1]
    for code, value in enumerate(table):
        if value == current[1]:
            current[0] = code
        else:
            found.append(current)
            current = [code, value]
    return found


def array(name, kind, values, per_line, doc):
    lines = [doc, "#[rustfmt::skip]", f"static {name}: [{kind}; {len(values)}] = ["]
    for start in range(0, len(values), per_line):
        lines.append("    " + " ".join(f"{value}," for value in values[start:start + per_line]))
    lines.append("];")
    return "\n".join(lines)


def render(found):
    ends = [f"0x{end:x}" for end, _ in found]
    values = [str(value) for _, value in found]
    return "\n".join([
        "//! The display cells a character takes when a source line is echoed: 0",
        "//! for a combining mark, 2 for a wide or fullwidth character, 1 for the",
        "//! rest, as GCC's `cpp_wcwidth` counts them (GCC manual, \"Diagnostic",
        "//! Message Formatting Options\", `-fdiagnostics-column-unit=display`).",
        f"//! Generated by `scripts/generate_cell_widths.py` from Unicode {UNICODE_VERSION},",
        "//! the version GCC 14's table follows; do not edit by hand.",
        "",
        "/// The cells `c` takes. Characters past the last run take one, as in GCC.",
        "pub(super) fn cell_width(c: char) -> usize {",
        "    let code = u32::from(c);",
        "    let run = RUN_ENDS.partition_point(|&end| end < code);",
        "    RUN_WIDTHS.get(run).map_or(1, |&width| usize::from(width))",
        "}",
        "",
        array("RUN_ENDS", "u32", ends, 8, "/// The last code point of each run of equal widths."),
        "",
        array("RUN_WIDTHS", "u8", values, 24, "/// The width of each run in `RUN_ENDS`."),
        "",
    ])


def main():
    arguments = [argument for argument in sys.argv[1:] if argument != "--check"]
    if len(arguments) != 1:
        sys.exit(f"usage: {sys.argv[0]} [--check] <directory with the UCD files>")
    text = render(runs(widths(Path(arguments[0]))))
    if "--check" in sys.argv[1:]:
        sys.exit(0 if OUT.exists() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
