#!/usr/bin/env python3
"""Generate the neutral builtin name index, preserving existing numeric IDs.

The scalar/library Rust shards are the contract source. New IDs are appended;
sorting names or inserting a shard row never renumbers an existing descriptor.
No LLVM trees or generated x86 tables are read or changed.
"""

from pathlib import Path
import re


def main():
    root = Path(__file__).resolve().parent.parent
    output = root / "src/builtins/index.rs"
    previous = output.read_text(encoding="utf-8") if output.exists() else ""
    ids = {name: int(number) for name, number in
           re.findall(r"^\s*(\w+)\s*=\s*(\d+),", previous, re.MULTILINE)}
    rows = []
    for shard in ("scalar", "library", "atomic"):
        source = (root / f"src/builtins/{shard}.rs").read_text(encoding="utf-8")
        for index, (identity, spelling) in enumerate(re.findall(
                r'descriptor\s*\(\s*Id::(\w+)\s*,\s*"([^"]+)"', source)):
            if identity not in ids:
                ids[identity] = max(ids.values(), default=-1) + 1
            rows.append((identity, spelling, shard, index))
    assert len({row[0] for row in rows}) == len(rows), "duplicate ID"
    assert len({row[1] for row in rows}) == len(rows), "duplicate spelling"
    text = '''//! Generated by `scripts/generate_builtin_index.py` from the contract shards.
//! IDs are append-only; the sorted name index is independent of shard order.
use super::{BuiltinDescriptor, atomic, library, scalar};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(u16)]
pub(crate) enum BuiltinId {
'''
    text += "".join(f"    {identity} = {ids[identity]},\n" for identity, _, _, _
                    in sorted(rows, key=lambda row: ids[row[0]]))
    text += '''}

impl BuiltinId {
    pub(crate) fn descriptor(self) -> &'static BuiltinDescriptor {
        match self {
'''
    text += "".join(f"            Self::{identity} => &{shard}::BUILTINS[{index}],\n"
                    for identity, _, shard, index in rows)
    text += '''        }
    }
}

pub(crate) fn lookup(spelling: &str) -> Option<&'static BuiltinDescriptor> {
    NAMES.binary_search_by_key(&spelling, |&(name, _)| name)
        .ok().map(|index| NAMES[index].1.descriptor())
}

#[cfg(test)]
pub(crate) fn descriptors() -> impl Iterator<Item = &'static BuiltinDescriptor> {
    NAMES.iter().map(|&(_, id)| id.descriptor())
}

const NAMES: &[(&str, BuiltinId)] = &[
'''
    text += "".join(f'    ("{spelling}", BuiltinId::{identity}),\n'
                    for identity, spelling, _, _ in sorted(rows, key=lambda row: row[1]))
    text += "];\n"
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"Indexed {len(rows)} builtin contracts with stable IDs")


if __name__ == "__main__":
    main()
