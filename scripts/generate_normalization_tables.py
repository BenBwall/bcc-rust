"""Generate the Unicode tables behind GCC's -Wnormalized check.

Writes src/translation_phases/preprocessor_tokenizer/ucn/composition.rs from
Python's `unicodedata`, whose Unicode version the file records. Run it with the
Python whose Unicode version bcc should follow and commit the result:

    python3 -I scripts/generate_normalization_tables.py

`--check` exits 1 instead of writing when the file would change.
"""
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/translation_phases/preprocessor_tokenizer/ucn/composition.rs"
CODE_POINTS = [c for c in range(0x110000) if not 0xD800 <= c <= 0xDFFF]


def pairs():
    """Each primary composite's two-character canonical decomposition."""
    found = []
    for code in CODE_POINTS:
        character = chr(code)
        fields = unicodedata.decomposition(character).split()
        if len(fields) != 2 or fields[0].startswith("<"):
            continue
        base, mark = (int(field, 16) for field in fields)
        if unicodedata.normalize("NFC", chr(base) + chr(mark)) == character:
            found.append(base << 32 | mark)
    return sorted(found)


def ranges(value):
    """Maximal runs of code points with the same non-default `value`."""
    runs = []
    for code in CODE_POINTS:
        current = value(code)
        if current is None:
            continue
        if runs and runs[-1][1] == code - 1 and runs[-1][2] == current:
            runs[-1][1] = code
        else:
            runs.append([code, code, current])
    return runs


def classes():
    return ranges(lambda code: unicodedata.combining(chr(code)) or None)


def never_in_nfc():
    return ranges(lambda code: True if unicodedata.normalize("NFC", chr(code)) != chr(code) else None)


def table(name, kind, values, per_line, doc):
    lines = [doc, "#[rustfmt::skip]", f"static {name}: [{kind}; {len(values)}] = ["]
    for start in range(0, len(values), per_line):
        lines.append("    " + " ".join(f"{value}," for value in values[start:start + per_line]))
    lines.append("];")
    return "\n".join(lines)


def hex64(value):
    text = f"{value:016X}"
    return "0x" + "_".join(text[i:i + 4] for i in range(0, 16, 4))


def render():
    version = unicodedata.unidata_version
    pair_values = [hex64(value) for value in pairs()]
    class_values = [hex64(start << 32 | end << 8 | ccc) for start, end, ccc in classes()]
    nfc_values = [hex64(start << 32 | end) for start, end, _ in never_in_nfc()]
    return f"""//! The Unicode {version} data for GCC's check that an identifier is in
//! Normalization Form C: the pairs canonical composition joins, each
//! character's canonical combining class, and the characters no text in the
//! form contains. Generated by `scripts/generate_normalization_tables.py`
//! from Python's `unicodedata`; do not edit by hand.
//!
//! C23: §6.4.2.1p3, p. 54; PDF p. 67 (Normalization Form C).

/// Whether canonical composition joins `mark` to `base` before it, when
/// nothing blocks them: whether `base` followed by `mark` spells one
/// precomposed character, as `a` followed by U+0300 spells `à`.
pub(super) fn composes(base: char, mark: char) -> bool {{
    let key = (u64::from(base) << 32) | u64::from(mark);
    PAIRS.binary_search(&key).is_ok()
}}

/// The canonical combining class of `character`: 0 for a starter.
pub(super) fn combining_class(character: char) -> u8 {{
    let code = u64::from(character);
    let index = CLASSES.partition_point(|&run| run >> 32 <= code);
    index
        .checked_sub(1)
        .map(|index| CLASSES[index])
        .filter(|&run| code <= (run >> 8) & 0xFF_FFFF)
        .map_or(0, |run| (run & 0xFF) as u8)
}}

/// Whether `character` never appears in Normalization Form C: a singleton
/// decomposition such as U+212B ANGSTROM SIGN, or a composite that
/// composition excludes.
pub(super) fn never_in_nfc(character: char) -> bool {{
    let code = u64::from(character);
    let index = NEVER_IN_NFC.partition_point(|&run| run >> 32 <= code);
    index
        .checked_sub(1)
        .is_some_and(|index| code <= NEVER_IN_NFC[index] & 0xFFFF_FFFF)
}}

{table("PAIRS", "u64", pair_values, 4, "/// Each primary composite's canonical decomposition `(base, mark)` as\n/// `base << 32 | mark`, sorted.")}

{table("CLASSES", "u64", class_values, 4, "/// Runs of characters with one non-zero canonical combining class, as\n/// `start << 32 | end << 8 | class`, sorted.")}

{table("NEVER_IN_NFC", "u64", nfc_values, 4, "/// Runs of characters Normalization Form C replaces, as\n/// `start << 32 | end`, sorted.")}
"""


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
