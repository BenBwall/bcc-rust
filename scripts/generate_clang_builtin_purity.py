#!/usr/bin/env python3
"""Generate `src/builtins/clang_purity.rs`: the builtins bcc knows that Clang
declares `const` or `pure`, from the pinned Clang's generated builtin tables.

Clang's `Sema::AddKnownFunctionAttributes` gives a builtin's declaration the
`const` attribute for the `c` letter of its attribute string (and for `g`,
whose condition, ignored floating-point exceptions, is Clang's default), and
for `e` only under `-fno-math-errno`; and `pure` for `U`. `Expr::HasSideEffects`
counts a call to such a function by its operands alone.

The tables are read from `<llvm>/include/clang/Basic/Builtins.inc` and the
x86 ones beside it, where `<llvm>` is the installed toolchain (`--llvm`,
`target/llvm` by default). The spellings bcc knows are read from
`src/builtins/index.rs` and the library shards' ordinary names. The output is
formatted with the repository's nightly rustfmt; `--check` compares instead
of writing.
"""

import argparse
from pathlib import Path
import re
import subprocess
import tempfile

TABLES = ("Builtins.inc", "BuiltinsX86.inc", "BuiltinsX86_64.inc")


def clang_attributes(basic):
    """Each builtin spelling's attribute string, as Clang's tables give it."""
    attributes = {}
    for table in TABLES:
        text = (basic / table).read_text(encoding="utf-8")
        for name, letters in re.findall(
                r"StrOffsets\{\d+ /\* (\S+) \*/, \d+ /\* \S* \*/, \d+ /\* (\S*) \*/", text):
            # The target tables name their builtins without the prefix.
            if table != "Builtins.inc" and not name.startswith("_"):
                name = "__builtin_ia32_" + name
            attributes.setdefault(name, letters)
    return attributes


def bcc_spellings(root):
    builtins = root / "src/builtins"
    names = set(re.findall(r'^\s*\("(\w+)", BuiltinId::\w+\),', (builtins / "index.rs").read_text(encoding="utf-8"),
                           re.MULTILINE))
    for shard in ("library.rs", "math.rs", "checked.rs"):
        text = (builtins / shard).read_text(encoding="utf-8")
        names.update(re.findall(r'"__builtin_\w+",\s*"(\w+)"', text))
    return names


def rust_list(name, doc, spellings):
    items = "".join(f'    "{spelling}",\n' for spelling in sorted(spellings))
    return f"{doc}const {name}: &[&str] = &[\n{items}];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llvm", type=Path, help="the installed LLVM toolchain (default: target/llvm)")
    parser.add_argument("--check", action="store_true", help="fail if src/builtins/clang_purity.rs differs")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    basic = (args.llvm or root / "target/llvm") / "include/clang/Basic"
    output = root / "src/builtins/clang_purity.rs"
    attributes = clang_attributes(basic)
    classes = {"CONST": [], "PURE": [], "CONST_WITHOUT_ERRNO": []}
    for spelling in bcc_spellings(root):
        letters = attributes.get(spelling)
        if letters is None:
            continue
        # The letters before a `:` are flags; `V:128:` and `p:0:` carry data.
        flags = letters.split(":")[0]
        if "c" in flags or "g" in flags:
            classes["CONST"].append(spelling)
        elif "U" in flags:
            classes["PURE"].append(spelling)
        elif "e" in flags:
            classes["CONST_WITHOUT_ERRNO"].append(spelling)
    text = '''//! Generated by `scripts/generate_clang_builtin_purity.py` from the pinned
//! Clang's builtin tables (`Builtins.inc` and the x86 ones); do not edit.
//!
//! The builtins bcc knows that Clang declares `const` or `pure`
//! (`Sema::AddKnownFunctionAttributes`), whose calls `Expr::HasSideEffects`
//! counts by their operands alone. A spelling not listed has neither.

/// The attribute Clang gives a builtin's declaration.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum ClangPurity {
    /// `const`: the attribute string's `c`, or `g`, which asks only that
    /// floating-point exceptions be ignored, as they are by default.
    Const,
    /// `pure`: `U`.
    Pure,
    /// `const` only under `-fno-math-errno`: `e`.
    ConstWithoutErrno,
}

/// The attribute Clang gives the declaration of the builtin `spelling`.
pub(crate) fn clang_purity(spelling: &str) -> Option<ClangPurity> {
    [
        (CONST, ClangPurity::Const),
        (PURE, ClangPurity::Pure),
        (CONST_WITHOUT_ERRNO, ClangPurity::ConstWithoutErrno),
    ]
    .into_iter()
    .find_map(|(list, purity)| list.binary_search(&spelling).is_ok().then_some(purity))
}

'''
    text += rust_list("CONST", "", classes["CONST"]) + "\n"
    text += rust_list("PURE", "", classes["PURE"]) + "\n"
    text += rust_list("CONST_WITHOUT_ERRNO", "", classes["CONST_WITHOUT_ERRNO"])
    with tempfile.TemporaryDirectory() as directory:
        generated = Path(directory) / "clang_purity.rs"
        generated.write_text(text, encoding="utf-8", newline="\n")
        subprocess.run(["rustfmt", "+nightly", "--edition", "2024",
                        "--config-path", str(root / ".rustfmt.toml"), str(generated)], check=True)
        text = generated.read_text(encoding="utf-8")
    previous = output.read_text(encoding="utf-8") if output.exists() else ""
    if args.check:
        if text != previous:
            raise SystemExit("src/builtins/clang_purity.rs differs; run scripts/generate_clang_builtin_purity.py")
    else:
        output.write_text(text, encoding="utf-8", newline="\n")
    print(", ".join(f"{len(spellings)} {name}" for name, spellings in classes.items()))


if __name__ == "__main__":
    main()
