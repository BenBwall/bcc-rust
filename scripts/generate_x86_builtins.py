"""Derive x86 builtin descriptors from shipped header calls.

Clang recognizes calls even with missing arguments. Its AST supplies canonical
signatures; independent valid probes check every signature on all bcc targets.
The result is the `src/builtins/x86.rs` registry shard; run
`scripts/generate_builtin_index.py` afterwards to assign stable IDs.
No Clang BuiltinsX86.td installation or compiler heap allocation is required.
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLANG = next((p for p in (ROOT / "target/llvm/bin/clang.exe", ROOT / "target/llvm/bin/clang") if p.exists()),
             ROOT / "target/llvm/bin/clang")
OUT = ROOT / "target/vector-builtins"
TRIPLES = ["x86_64-unknown-linux-gnu", "x86_64-unknown-linux-musl", "x86_64-w64-windows-gnu", "x86_64-pc-windows-msvc"]
SCALARS = {"void":"v", "char":"c", "signed char":"a", "unsigned char":"A", "short":"s", "unsigned short":"S", "int":"i", "unsigned int":"I", "long":"l", "unsigned long":"L", "long long":"q", "unsigned long long":"Q", "float":"f", "double":"d"}
SIZES = {"c":1,"a":1,"A":1,"s":2,"S":2,"i":4,"I":4,"q":8,"Q":8,"f":4,"d":8}

def run(path, *flags):
    return subprocess.run([str(CLANG), "-std=c11", "-fsyntax-only", "-ferror-limit=0", *flags, str(path)], capture_output=True, text=True)

def json_nodes(text):
    decoder = json.JSONDecoder()
    index = 0
    while index < len(text):
        while index < len(text) and text[index].isspace(): index += 1
        if index == len(text): break
        node, index = decoder.raw_decode(text,index)
        yield node

def encode(text):
    if text.endswith(" *"): return "P" + encode(text[:-2])
    if text.startswith("const "): return "C" + encode(text[6:])
    if text.endswith(" const"): return "C" + encode(text[:-6])
    if text.startswith("__attribute__"):
        m = re.search(r"__vector_size__\((\d+) \* sizeof\((.*?)\)\)",text)
        assert m, text
        return "V" + m[1] + SCALARS[m[2]]
    return SCALARS[text]

HEADER = """//! Generated by `scripts/generate_x86_builtins.py` from Clang header call
//! signatures; do not edit. Regenerate, then run
//! `scripts/generate_builtin_index.py`.
//!
//! GNU extension: GCC manual, "x86 Built-in Functions", documents these
//! builtins and their constant operands.
//! <https://gcc.gnu.org/onlinedocs/gcc/x86-Built-in-Functions.html>
//!
//! Each descriptor records a signature, verified on all four targets, and
//! the immediate-operand limits that `semantic_analysis/builtins/x86_builtins.rs`
//! checks after prototype conversion. Lowering has no x86 instructions; the
//! operation keeps the existing refusal rather than an external call.
//! Header calls that name a scalar registry spelling are listed in
//! `MERGED`: those spellings keep their one scalar descriptor.
//! C99: §6.5.2.2 paragraph 7, p. 72; PDF p. 84 (prototype conversion).
use super::{
    ArgumentRule as A,
    Availability,
    BuiltinDescriptor,
    BuiltinEffectClass,
    BuiltinId as Id,
    BuiltinOperation,
    ConstantConstraint,
    ConstraintDiagnostic,
    ConversionRule,
    DesignatorPolicy,
    NamingPolicy,
    Signature,
    SignatureType as T,
    SyntaxForm,
    TypeRule,
    UnsupportedReason,
};
use crate::{
    configuration::Feature,
    target::Scalar as S,
};

"""
FOOTER = """
/// A prototyped x86 builtin. The checker reports [`Feature::VectorBuiltins`]
/// when a call first binds the spelling.
const fn x86(
    id: Id,
    spelling: &'static str,
    result: T,
    parameters: &'static [T],
    arguments: &'static [A],
) -> BuiltinDescriptor {
    BuiltinDescriptor {
        id,
        spelling,
        availability: Availability {
            feature: Some(Feature::VectorBuiltins),
            naming:  NamingPolicy::Reserved,
        },
        syntax: SyntaxForm::OrdinaryCall,
        designator: DesignatorPolicy::DirectCallOnly,
        signature: Signature {
            result,
            parameters,
            prototype: true,
            variadic: false,
        },
        type_rule: TypeRule::X86Signature,
        arguments,
        arity: (parameters.len(), parameters.len()),
        effects: BuiltinEffectClass::Unknown,
        operation: BuiltinOperation::Unsupported(UnsupportedReason::X86),
        library: None,
    }
}

/// An operand converted to its prototype parameter.
const P: A = A::value(ConversionRule::Prototype);

/// An immediate: after prototype conversion, an integer constant expression
/// in `[low, high]` and, with a nonzero mask, a set bit of `mask`.
const fn imm(low: i32, high: i32, mask: u16) -> A {
    A::constrained(
        ConversionRule::Prototype,
        ConstantConstraint::Immediate(low, high, mask),
        ConstraintDiagnostic::Immediate,
    )
}
"""
SCALAR_NAMES = {"v":"VOID", "c":"CHAR", "a":"SCHAR", "A":"UCHAR", "s":"SHORT", "S":"USHORT", "i":"INT", "I":"UINT", "l":"LONG", "L":"ULONG", "q":"LLONG", "Q":"ULLONG", "f":"FLOAT", "d":"DOUBLE"}
SCALAR_RUST = {"v":"Void", "c":"Char", "a":"SignedChar", "A":"UnsignedChar", "s":"Short", "S":"UnsignedShort", "i":"Int", "I":"UnsignedInt", "l":"Long", "L":"UnsignedLong", "q":"LongLong", "Q":"UnsignedLongLong", "f":"Float", "d":"Double"}


def rust_type(code):
    """A signature encoding as an alias name and its `SignatureType`."""
    pointer = code.startswith("P")
    rest = code[1:] if pointer else code
    constant = rest.startswith("C")
    rest = rest[1:] if constant else rest
    scalar = rest[-1]
    name = ("P_" if pointer else "") + ("C_" if constant else "")
    if rest.startswith("V"):
        count = int(rest[1:-1])
        name += f"V{count}_{SCALAR_NAMES[scalar]}"
        assert not constant or pointer, code
        value = (f"T::VectorPointer(S::{SCALAR_RUST[scalar]}, {count}, {str(constant).lower()})"
                 if pointer else f"T::Vector(S::{SCALAR_RUST[scalar]}, {count})")
    else:
        name += SCALAR_NAMES[scalar]
        assert not constant or pointer, code
        value = (f"T::Pointer(S::{SCALAR_RUST[scalar]}, {str(constant).lower()})"
                 if pointer else f"T::Scalar(S::{SCALAR_RUST[scalar]})")
    return name, value


def identity(name):
    """The stable `BuiltinId` variant of an x86 spelling."""
    suffix = name.removeprefix("__builtin_ia32_")
    return "X86" + "".join(part[:1].upper() + part[1:] for part in suffix.split("_"))


def scalar_spellings():
    """Spellings the handwritten scalar shard owns; the x86 shard merges them."""
    source = (ROOT/"src/builtins/scalar.rs").read_text(encoding="utf-8")
    return set(re.findall(r'descriptor\s*\(\s*Id::\w+\s*,\s*"([^"]+)"', source))


def emit(specs, ranges):
    """Writes the registry shard from verified specs and immediate ranges."""
    merged = scalar_spellings()
    aliases = {}
    rows = []
    merged_rows = []
    identities = set()
    for idx, (name, _, _, codes, immediates) in enumerate(specs):
        if name in merged:
            merged_rows.append(f'    ("{name}", "{",".join(codes)}"),')
            continue
        assert name.startswith("__builtin_ia32_"), name
        for code in codes:
            alias, value = rust_type(code)
            assert aliases.setdefault(alias, value) == value, code
        names = [rust_type(code)[0] for code in codes]
        arguments = ["imm(" + ", ".join(f"{v:_}" for v in ranges.get((idx, j), (-2147483648, 2147483647, 0))) + ")"
                     if j in immediates else "P" for j in range(len(codes) - 1)]
        ident = identity(name)
        assert ident not in identities, ident
        identities.add(ident)
        rows.append(f'    x86(Id::{ident}, "{name}", {names[0]}, &[{", ".join(names[1:])}], &[{", ".join(arguments)}]),')
    text = HEADER
    text += "".join(f"const {alias}: T = {value};\n" for alias, value in sorted(aliases.items()))
    text += "\n/// Clang x86 intrinsic contracts in header-discovery order.\n#[rustfmt::skip]\n"
    text += "pub(super) const BUILTINS: &[BuiltinDescriptor] = &[\n" + "\n".join(rows) + "\n];\n"
    text += "\n/// Header calls owned by the scalar shard, with the Clang signature each\n"
    text += "/// scalar descriptor must agree with (checked by the registry tests).\n"
    text += "#[cfg(test)]\n#[rustfmt::skip]\n"
    text += "pub(crate) const MERGED: &[(&str, &str)] = &[\n" + "\n".join(merged_rows) + "\n];\n"
    text += FOOTER
    (ROOT/"src/builtins/x86.rs").write_text(text, encoding="utf-8", newline="\n")
    return len(rows), len(merged_rows)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    names = sorted(set(re.findall(r"\b__builtin_ia32_\w+", "\n".join(p.read_text() for p in (ROOT/"src/headers").glob("*.h")))) | {"__builtin_popcount", "__builtin_popcountll"})
    discovery = OUT/"discover.c"
    discovery.write_text("void f(void) {\n" + "\n".join(n+"();" for n in names) + "\n}\n")
    result = run(discovery,"-Xclang","-ast-dump=json","-Xclang","-ast-dump-filter=__builtin_")
    nodes = {n["name"]:n for n in json_nodes(result.stdout) if n.get("kind")=="FunctionDecl"}
    assert set(names) == nodes.keys(), set(names)-nodes.keys()
    types = {}
    specs = []
    for name in names:
        node = nodes[name]
        params = [n["type"]["qualType"] for n in node.get("inner",[]) if n["kind"]=="ParmVarDecl"]
        suffix = " (" + (", ".join(params) if params else "void") + ")"
        qt = node["type"]["qualType"]
        assert qt.endswith(suffix), qt
        result = qt[:-len(suffix)]
        encodings = [encode(t) for t in [result,*params]]
        for t in [result,*params]: types.setdefault(t,"T"+str(len(types)))
        specs.append([name,result,params,encodings,[]])
    typedefs = []
    aliases = {}
    reverse = {v:k for k,v in SCALARS.items()}
    def alias(code):
        if code in aliases: return aliases[code]
        if code.startswith("P"): base = alias(code[1:])+" *"
        elif code.startswith("C"): base = "const "+alias(code[1:])
        elif code.startswith("V"):
            count=int(code[1:-1]);scalar=code[-1]
            base=reverse[scalar]
        else:base=reverse[code]
        name="U"+str(len(aliases))
        aliases[code]=name
        attr = f" __attribute__((vector_size({count*SIZES[scalar]})))" if code.startswith("V") else ""
        typedefs.append(f"typedef {base} {name}{attr};")
        return name
    for text in types: types[text]=alias(encode(text))
    prefix = "\n".join(typedefs)+"\n"
    lines = []
    cases = {}
    for idx,(name,result,params,_,_) in enumerate(specs):
        declarations = ", ".join(types[t]+" p"+str(j) for j,t in enumerate(params)) or "void"
        for j,t in enumerate(params):
            if t not in ["int","unsigned int","char","short","unsigned char","unsigned short","long long","unsigned long long"]:continue
            args = ["p"+str(k) if k==j or pt not in SCALARS or pt in ["float","double"] else "1" for k,pt in enumerate(params)]
            lines.append("void probe_"+str(idx)+"_"+str(j)+"("+declarations+") { (void)"+name+"("+", ".join(args)+"); }")
            cases[len(prefix.splitlines())+len(lines)]=(idx,j)
    path = OUT/"immediates.c";path.write_text(prefix+"\n".join(lines)+"\n")
    result = run(path)
    for m in re.finditer(r"immediates.c:(\d+):\d+: error: (.*)",result.stderr):
        if "constant integer" in m[2] or "must be a constant" in m[2]:
            idx,j = cases[int(m[1])]
            specs[idx][4].append(j)
        else: raise RuntimeError(m[0])
    range_lines=[]
    range_cases={}
    ranges={}
    for idx,(name,result,params,_,immediates) in enumerate(specs):
        declarations = ", ".join(types[t]+" p"+str(j) for j,t in enumerate(params)) or "void"
        for j in immediates:
            args=["-1" if k==j else "1" if k in immediates else "p"+str(k) for k in range(len(params))]
            range_lines.append("void range_"+str(idx)+"_"+str(j)+"("+declarations+") { (void)"+name+"("+", ".join(args)+"); }")
            range_cases[len(prefix.splitlines())+len(range_lines)]=(idx,j)
    path=OUT/"ranges.c";path.write_text(prefix+"\n".join(range_lines)+"\n")
    result=run(path)
    (OUT/"ranges.stderr").write_text(result.stderr)
    for m in re.finditer(r"ranges.c:(\d+):\d+: error: (.*)",result.stderr):
        idx,j=range_cases[int(m[1])]
        limits=re.search(r"range \[(-?\d+), ?(-?\d+)\]",m[2])
        if limits:ranges[(idx,j)]=(int(limits[1]),int(limits[2]),0)
        elif "scale" in m[2]:ranges[(idx,j)]=(1,8,278)
        else:raise RuntimeError(m[0])
    valid = []
    for idx,(name,result,params,_,immediates) in enumerate(specs):
        declarations = ", ".join(types[t]+" p"+str(j) for j,t in enumerate(params)) or "void"
        args = ["1" if j in immediates else "p"+str(j) for j in range(len(params))]
        call=name+"("+", ".join(args)+")"
        valid.append("void verify_"+str(idx)+"("+declarations+") { _Static_assert(__builtin_types_compatible_p(__typeof__("+call+"), "+types[result]+"), \"signature\"); (void)"+call+"; }")
    path=OUT/"verified.c";path.write_text(prefix+"\n".join(valid)+"\n")
    for triple in TRIPLES:
        result=run(path,"--target="+triple)
        (OUT/(triple+".stderr")).write_text(result.stderr)
        assert result.returncode==0,result.stderr[:3000]
    count, merged = emit(specs, ranges)
    print(f"Verified {len(specs)} signatures on all four targets; {sum(bool(s[4]) for s in specs)} have constant operands; "
          f"emitted {count} x86 descriptors and {merged} merged scalar spellings.")

if __name__ == "__main__": main()
