//! The compiler pipeline view's data: what bcc produces at each stage for a
//! program, from the logical lines of translation phases 1-2 to machine
//! code, the explanation of each stage with the C99 rules it applies, the
//! links between source lines and output lines, why a failed compilation
//! stopped, and what the optimizer changed. The front-end phases' own data
//! is in `pipeline/front_end.rs`.
//!
//! Every stage but LLVM IR comes from bcc's real compiler, run in the
//! compiler Worker (`explorer.rs`), for the bundled lessons as for edited
//! source, so a lesson's view is exactly what the in-browser compiler makes of
//! it. The browser build has no LLVM, so the lessons carry LLVM IR
//! precomputed by the native compiler at both optimization levels, with the
//! source line of each of its lines (`web/pipeline/`, regenerated by
//! `web/pipeline/generate.sh`).

