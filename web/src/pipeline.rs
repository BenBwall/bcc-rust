/// The most source text the page compiles, in bytes: the in-browser
/// compiler's limit (`bcc_rust::explorer::WASM_MAX_SOURCE_BYTES`). There
/// each of the compiler's arenas is one fixed 32 MiB region of memory, and
/// 64 KiB of any ordinary program fits them, compiling within the page's
/// ten seconds.
pub const MAX_COMPILE_BYTES: usize = 64 * 1024;

/// How the page's refusal of a program larger than [`MAX_COMPILE_BYTES`]
/// begins.
pub const TOO_LARGE: &str = "Too large for the in-browser compiler: ";

/// Why the page does not compile `source`, if it is larger than
/// [`MAX_COMPILE_BYTES`].
pub fn too_large(source: &str) -> Option<String> {
    (source.len() > MAX_COMPILE_BYTES).then(|| {
        format!(
            "{TOO_LARGE}this program is {} KiB, and bcc's in-browser compiler takes at most {} \
             KiB of source, so the page did not compile it. Each of the compiler's memory arenas \
             is a fixed region in the browser, and larger programs can fill one. Make the program \
             smaller, or compile it with the native bcc.",
            source.len().div_ceil(1024),
            MAX_COMPILE_BYTES / 1024
        )
    })
}

/// bcc's output for one program, one field per stage.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Compilation {
    /// The logical lines translation phases 1 and 2 leave, one per line.
    pub logical:            Option<String>,
    /// Each of those lines' physical lines and what changed in it.
    pub logical_lines:      Vec<LogicalLine>,
    /// Phase 3's preprocessing tokens and white space, one per line.
    pub pp_tokens:          Option<String>,
    /// Where each of those lines' entry is in the source.
    pub pp_ranges:          Vec<SourceSpan>,
    /// How many entries of each kind phase 3 made, in listing order.
    pub pp_counts:          Vec<(String, usize)>,
    /// The comments phase 3 replaced by one space each.
    pub pp_comments:        Vec<SourceSpan>,
    /// The text phase 4 leaves, with line markers, laid out as `-E` lays
    /// it out.
    pub preprocessed:       Option<String>,
    /// Where each line of it came from.
    pub preprocessed_lines: Vec<OutputLine>,
    /// What phase 4 did in the source.
    pub preprocessing:      Preprocessing,
    pub tokens:             Option<String>,
    pub syntax_tree:        Option<String>,
    /// Semantic analysis's scopes, declarations and expression types.
    pub semantic_types:     Option<String>,
    pub ir:                 Option<String>,
    pub ir_abi:             Option<String>,
    /// Where each line of `ir` came from.
    pub ir_lines:           Vec<LineOrigin>,
    /// The same for `ir_abi`.
    pub ir_abi_lines:       Vec<LineOrigin>,
    /// LLVM IR; only the native compiler produces it.
    pub llvm:               Option<String>,
    /// The same for `llvm`, recorded with it.
    pub llvm_lines:         Vec<LineOrigin>,
    pub asm:                Option<String>,
    /// The same for `asm`.
    pub asm_lines:          Vec<LineOrigin>,
    /// Offset, encoded bytes and instruction, one line per instruction.
    pub machine_code:       Option<String>,
    /// The same for `machine_code`: its instruction's line of the assembly's.
    pub machine_code_lines: Vec<LineOrigin>,
    /// The machine code's size in bytes.
    pub code_bytes:         usize,
    pub diagnostics:        Vec<CompileDiagnostic>,
    /// Which output lines each function definition became.
    pub functions:          Vec<FunctionLines>,
}

/// One of bcc's diagnostics, placed in the editor's coordinates.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompileDiagnostic {
    /// `error`, `warning` or `note`.
    pub severity: String,
    /// `front-end`, `middle-end` or `back-end`.
    pub stage:    String,
    pub message:  String,
    /// The range in the edited source, as 1-based lines and UTF-16 columns
    /// (the end column just past the range); `None` for a diagnostic with no
    /// place, or one in a header.
    pub range:    Option<SourceSpan>,
    /// The diagnostic as the command line prints it, with its source excerpt.
    pub rendered: String,
}

#[derive(Clone, Copy, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SourceSpan {
    pub line:       usize,
    pub column:     usize,
    pub end_line:   usize,
    pub end_column: usize,
}

/// Where one line of a back-end stage's output came from, read from the
/// compiler's debug locations (`bcc_rust::explorer::ExplorerLineOrigin`).
#[derive(Clone, Copy, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct LineOrigin {
    /// The source line its instruction came from, or 0.
    pub line: usize,
    /// For an instruction inlined from another function, the source line of
    /// the call it was copied for, or 0.
    pub call: usize,
    /// Whether the line is an instruction: one with no `line` is code that no
    /// source line can claim, where a label simply has none.
    pub code: bool,
}

/// One function definition's lines (1-based, inclusive) in the source and in
/// each output. A line of the output links on its own ([`LineOrigin`]) unless
/// no line of it has a source line; a function's header stands for all of it.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FunctionLines {
    pub name:         String,
    pub source:       (usize, usize),
    pub ir:           Option<(usize, usize)>,
    pub ir_abi:       Option<(usize, usize)>,
    pub asm:          Option<(usize, usize)>,
    pub machine_code: Option<(usize, usize)>,
}

impl FunctionLines {
    fn output(&self, stage: Stage) -> Option<(usize, usize)> {
        match stage {
            | Stage::Ir => self.ir,
            | Stage::IrAbi => self.ir_abi,
            | Stage::Asm => self.asm,
            | Stage::MachineCode => self.machine_code,
            | Stage::Lines
            | Stage::PpTokens
            | Stage::Preprocessor
            | Stage::Tokens
            | Stage::SyntaxTree
            | Stage::SemanticTypes
            | Stage::Llvm => None,
        }
    }
}

impl Compilation {
    /// The source lines of the function definition holding `line`, if any.
    pub fn function_around(&self, line: usize) -> Option<(usize, usize)> {
        self.functions
            .iter()
            .map(|function| function.source)
            .find(|&(first, last)| (first..=last).contains(&line))
    }

    /// Where each line of a back-end `stage`'s output came from; empty for
    /// the stages that place their lines otherwise.
    pub fn origins(&self, stage: Stage) -> &[LineOrigin] {
        match stage {
            | Stage::Ir => &self.ir_lines,
            | Stage::IrAbi => &self.ir_abi_lines,
            | Stage::Llvm => &self.llvm_lines,
            | Stage::Asm => &self.asm_lines,
            | Stage::MachineCode => &self.machine_code_lines,
            | Stage::Lines
            | Stage::PpTokens
            | Stage::Preprocessor
            | Stage::Tokens
            | Stage::SyntaxTree
            | Stage::SemanticTypes => &[],
        }
    }

    /// The output of `stage`.
    pub fn output(&self, stage: Stage) -> Option<&str> {
        match stage {
            | Stage::Lines => self.logical.as_deref(),
            | Stage::PpTokens => self.pp_tokens.as_deref(),
            | Stage::Preprocessor => self.preprocessed.as_deref(),
            | Stage::Tokens => self.tokens.as_deref(),
            | Stage::SyntaxTree => self.syntax_tree.as_deref(),
            | Stage::SemanticTypes => self.semantic_types.as_deref(),
            | Stage::Ir => self.ir.as_deref(),
            | Stage::IrAbi => self.ir_abi.as_deref(),
            | Stage::Llvm => self.llvm.as_deref(),
            | Stage::Asm => self.asm.as_deref(),
            | Stage::MachineCode => self.machine_code.as_deref(),
        }
        .filter(|text| !text.trim().is_empty())
    }

    /// Why bcc stopped before the last stage, if an error stopped it.
    pub fn stop(&self) -> Option<Stop> {
        let error = self
            .diagnostics
            .iter()
            .find(|diagnostic| diagnostic.severity == "error")?;
        let at = error
            .range
            .map_or_default(|range| format!(" on line {}", range.line));
        let message = &error.message;
        let (phase, explanation) = match error.stage.as_str() {
            | "middle-end" => (
                "Middle end",
                format!(
                    "The front end accepted your program, but bcc could not lower it into its \
                     IR{at}: “{message}”. This is usually a part of C that bcc does not translate \
                     yet, not a mistake in your program, so the IR, assembly and machine code \
                     stages have nothing to show."
                ),
            ),
            | "back-end" => (
                "Back end",
                format!(
                    "The IR is complete, but bcc's own x86-64 back end cannot turn it into \
                     assembly yet: “{message}”. That is a gap in bcc, not in your program. The IR \
                     stages still show what the middle end made of it."
                ),
            ),
            | _ if let Some(include) = self.missing_header(error) => (
                "Front end",
                format!(
                    "bcc could not find the header {include}{at}. Your browser has no C library \
                     of its own, so bcc finds only the headers it brings: the freestanding ones, \
                     such as <limits.h>, <stdint.h> and <stddef.h>, and those of its own small C \
                     library, such as <stdio.h>, <stdlib.h>, <string.h>, <ctype.h> and <math.h>. \
                     A header outside that set, such as <pthread.h> or another library's, needs \
                     the command-line bcc and a full C library."
                ),
            ),
            | _ => (
                "Front end",
                format!(
                    "bcc found an error in your program{at}: “{message}”. The front-end stages \
                     show how far it got (the preprocessor and the parser recover so they can \
                     report more than one error), but bcc translates only a program without \
                     errors, so the IR, assembly and machine code stages did not run. Fix the \
                     code with the red squiggle and the pipeline compiles again as you type."
                ),
            ),
        };
        Some(Stop {
            phase,
            explanation,
            line: error.range.map(|range| range.line),
        })
    }

    /// The header, as written, whose `#include` on the line of `error` was
    /// not found.
    fn missing_header(&self, error: &CompileDiagnostic) -> Option<String> {
        let line = error.range?.line;
        self.preprocessing
            .includes
            .iter()
            .find(|include| !include.found && include.line == line)
            .map(Include::spelled)
    }

    /// Whether `stage` should have run but an error stopped bcc first.
    pub fn stopped_before(&self, stage: Stage) -> bool {
        stage != Stage::Llvm && self.output(stage).is_none() && self.stop().is_some()
    }
}

/// Where and why a compilation stopped.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Stop {
    /// The part of the compiler that reported the error.
    pub phase:       &'static str,
    /// What happened and what it means, for programmers new to compilers.
    pub explanation: String,
    pub line:        Option<usize>,
}

/// One stage of the pipeline, in compilation order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Stage {
    /// Translation phases 1-2: characters and logical lines.
    Lines,
    /// Phase 3: preprocessing tokens.
    PpTokens,
    /// Phase 4: the preprocessor.
    Preprocessor,
    /// Phases 5-7: tokens.
    Tokens,
    SyntaxTree,
    /// Phase 7's semantic analysis: declarations and expression types.
    SemanticTypes,
    Ir,
    IrAbi,
    Llvm,
    Asm,
    MachineCode,
}

