/// How the lines of one stage's output relate to the source lines.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Links {
    /// For each output line (1-based, index 0 unused), the source lines it
    /// came from (first and last, inclusive), for stages that record
    /// locations.
    exact:     Option<LineLinks>,
    /// For each output line, where exactly in the source it is, for stages
    /// that list one source range per line.
    ranges:    Vec<SourceSpan>,
    /// Otherwise each function's source lines and output lines, inclusive.
    functions: FunctionSpans,
    /// For a back-end stage, where each output line came from.
    origins:   Vec<LineOrigin>,
    /// Which output lines each source line links to, sorted, so a hover need
    /// not walk the output: see [`Links::outputs_for`].
    outputs:   Vec<(usize, usize)>,
    /// The output lines that link to a range of source lines with no output
    /// line of its own, and the range: a body the optimizer rebuilt.
    spans:     Vec<(usize, usize, usize)>,
}

/// For each output line (1-based, index 0 unused), the first and last
/// source lines it came from, if any.
pub type LineLinks = Vec<Option<(usize, usize)>>;

/// Each function's source lines and output lines, inclusive.
type FunctionSpans = Vec<((usize, usize), (usize, usize))>;

impl Links {
    /// Links with each output line's own place, `exact`.
    fn exact(exact: LineLinks, ranges: Vec<SourceSpan>, origins: Vec<LineOrigin>) -> Self {
        let mut own: Vec<usize> = exact
            .iter()
            .flatten()
            .filter(|(first, last)| first == last)
            .map(|&(first, _)| first)
            .collect();
        own.sort_unstable();
        own.dedup();
        let has_own = |first: usize, last: usize| {
            own.get(own.partition_point(|&each| each < first))
                .is_some_and(|&each| each <= last)
        };
        let mut outputs = Vec::new();
        let mut spans = Vec::new();
        for (output, link) in exact.iter().enumerate() {
            let Some(&(first, last)) = link.as_ref() else {
                continue;
            };
            if first != last && !has_own(first, last) {
                spans.push((first, last, output));
            } else {
                outputs.push((first, output));
                if first != last {
                    outputs.push((last, output));
                }
            }
        }
        for (index, origin) in origins.iter().enumerate() {
            if origin.call != 0 && origin.call != origin.line {
                outputs.push((origin.call, index + 1));
            }
        }
        outputs.sort_unstable();
        Self {
            exact: Some(exact),
            ranges,
            functions: Vec::new(),
            origins,
            outputs,
            spans,
        }
    }

    /// Output lines that came from `line` of the source: those it alone
    /// became, and the inlined copies made for a call on it. An output line
    /// linked to several source lines (an IR function's header or closing
    /// brace, which stand for the whole function, or a logical line spliced
    /// from several) counts for the lines at either end, and for those
    /// between only when none of them has an output line of its own, as in
    /// a body the optimizer rebuilt: the statements of a function are not
    /// "what became" of its header.
    pub fn outputs_for(&self, line: usize) -> Vec<usize> {
        if self.exact.is_some() {
            let start = self.outputs.partition_point(|&(source, _)| source < line);
            let mut linked: Vec<usize> = self.outputs[start..]
                .iter()
                .take_while(|&&(source, _)| source == line)
                .map(|&(_, output)| output)
                .chain(
                    self.spans
                        .iter()
                        .filter(|&&(first, last, _)| (first..=last).contains(&line))
                        .map(|&(_, _, output)| output),
                )
                .collect();
            linked.sort_unstable();
            linked.dedup();
            return linked;
        }
        self.functions
            .iter()
            .filter(|(source, _)| (source.0..=source.1).contains(&line))
            .flat_map(|(_, output)| output.0..=output.1)
            .collect()
    }

    /// The output line to scroll to for `line` of the source: the first
    /// that came from that line alone (an IR instruction rather than its
    /// function's header), else the first linked at all.
    pub fn first_output_for(&self, line: usize) -> Option<usize> {
        let outputs = self.outputs_for(line);
        self.exact
            .as_ref()
            .and_then(|exact| {
                outputs
                    .iter()
                    .copied()
                    .find(|&output| exact[output] == Some((line, line)))
            })
            .or_else(|| outputs.first().copied())
    }

    /// Source lines that `line` of the output came from.
    pub fn sources_for(&self, line: usize) -> Vec<usize> {
        if let Some(exact) = &self.exact {
            return exact
                .get(line)
                .copied()
                .flatten()
                .map_or_else(Vec::new, |(first, last)| (first..=last).collect());
        }
        self.functions
            .iter()
            .filter(|(_, output)| (output.0..=output.1).contains(&line))
            .flat_map(|(source, _)| source.0..=source.1)
            .collect()
    }

    /// Where `line` of a back-end stage's output came from.
    pub fn origin(&self, line: usize) -> LineOrigin {
        line.checked_sub(1)
            .and_then(|index| self.origins.get(index))
            .copied()
            .unwrap_or_default()
    }

    /// The output lines of a back-end stage that are code no source line can
    /// claim.
    pub fn unclaimed(&self) -> impl Iterator<Item = usize> + '_ {
        self.origins
            .iter()
            .enumerate()
            .filter(|(_, origin)| origin.code && origin.line == 0)
            .map(|(index, _)| index + 1)
    }

    /// Where exactly in the source `line` of the output is, when the stage
    /// lists one source range per line.
    pub fn range_for(&self, line: usize) -> Option<SourceSpan> {
        line.checked_sub(1)
            .and_then(|index| self.ranges.get(index))
            .copied()
    }

    /// Whether lines link one to one rather than per function.
    pub fn is_exact(&self) -> bool {
        self.exact.is_some()
    }

    pub fn is_empty(&self) -> bool {
        self.exact.is_none() && self.functions.is_empty()
    }

    /// Whether this is a back-end stage's links, read from debug locations.
    pub fn has_origins(&self) -> bool {
        self.exact.is_some() && !self.origins.is_empty()
    }
}

/// What the view shows for `stage`: its output, with the preprocessor's
/// headers folded unless `headers`, and each output line's source lines
/// when the view rewrites the output.
pub fn displayed(
    stage: Stage,
    compilation: &Compilation,
    headers: bool,
) -> Option<(String, Option<LineLinks>)> {
    let output = compilation.output(stage)?;
    if stage != Stage::Preprocessor {
        return Some((output.to_owned(), None));
    }
    let view = front_end::preprocessed_view(
        output,
        &compilation.preprocessed_lines,
        &compilation.preprocessing.includes,
        !headers,
    );
    Some((view.text, Some(view.links)))
}

/// The gutter labels of `stage`'s view: the physical lines of each logical
/// line, and the source line of each preprocessed line. Other views number
/// their lines.
pub fn gutter(stage: Stage, compilation: &Compilation, headers: bool) -> Vec<String> {
    match stage {
        | Stage::Lines => line_labels(&compilation.logical_lines),
        | Stage::Preprocessor => compilation.output(stage).map_or_else(Vec::new, |output| {
            front_end::preprocessed_view(
                output,
                &compilation.preprocessed_lines,
                &compilation.preprocessing.includes,
                !headers,
            )
            .labels
        }),
        | _ => Vec::new(),
    }
}

/// The links between `source` and `stage`'s output in `compilation`, as
/// the view shows it (`headers` for the preprocessor's). Every front-end
/// stage places each line: the logical lines by the physical lines they
/// were spliced from, preprocessing tokens by their exact range, the
/// preprocessed text by its line markers, and tokens and the syntax tree by
/// their location. Each back-end stage links each instruction to the line its
/// debug location names ([`origin_links`]), the LLVM IR of a lesson by the
/// table recorded with it. A program with no located line links per function.
pub fn links(stage: Stage, compilation: &Compilation, source: &str, headers: bool) -> Links {
    let Some((output, rewritten)) = displayed(stage, compilation, headers) else {
        return Links::default();
    };
    let exact = match stage {
        | Stage::Lines => Some(
            std::iter::once(None)
                .chain(
                    compilation
                        .logical_lines
                        .iter()
                        .map(|line| Some(line.source)),
                )
                .collect(),
        ),
        | Stage::PpTokens => Some(
            std::iter::once(None)
                .chain(
                    compilation
                        .pp_ranges
                        .iter()
                        .map(|range| Some((range.line, range.end_line.max(range.line)))),
                )
                .collect(),
        ),
        | Stage::Preprocessor => rewritten,
        | Stage::Ir | Stage::IrAbi | Stage::Llvm | Stage::Asm | Stage::MachineCode => {
            let functions = function_lines(stage, compilation, source, &output);
            let origins = compilation.origins(stage);
            return match origin_links(origins, &functions) {
                | Some(exact) => Links::exact(exact, Vec::new(), origins.to_vec()),
                | None => Links {
                    functions,
                    ..Links::default()
                },
            };
        },
        | _ => stage.locations().map(|locate| {
            std::iter::once(None)
                .chain(
                    output
                        .lines()
                        .map(|line| locate(line).map(|line| (line, line))),
                )
                .collect()
        }),
    };
    let ranges = if stage == Stage::PpTokens {
        compilation.pp_ranges.clone()
    } else {
        Vec::new()
    };
    exact.map_or_else(Links::default, |exact| Links::exact(exact, ranges, Vec::new()))
}

/// Each function's source lines and lines in `output`, `stage`'s text. The
/// compiler's line map places them, and for a lesson's LLVM IR its function
/// headers do: without a live compilation (still loading), the definitions
/// are found in the source.
fn function_lines(
    stage: Stage,
    compilation: &Compilation,
    source: &str,
    output: &str,
) -> FunctionSpans {
    if stage != Stage::Llvm {
        return compilation
            .functions
            .iter()
            .filter_map(|function| Some((function.source, function.output(stage)?)))
            .collect();
    }
    let defined: Vec<(String, (usize, usize))> = if compilation.functions.is_empty() {
        function_spans(source, source_function)
    } else {
        compilation
            .functions
            .iter()
            .map(|function| (function.name.clone(), function.source))
            .collect()
    };
    function_spans(output, llvm_function)
        .into_iter()
        .filter_map(|(name, output)| {
            defined
                .iter()
                .find(|(defined, _)| *defined == name)
                .map(|(_, source)| (*source, output))
        })
        .collect()
}

/// A back-end stage's links: each instruction to the source line it came
/// from, and a function's first and last line to the whole function when they
/// are not code (a header, a label, a closing brace, a directive). A function
/// none of whose lines kept a source line links every line to the whole
/// function. `None` when no line has a source line (a program of declarations,
/// or a stage with no table), so the stage links per function and says so.
fn origin_links(
    origins: &[LineOrigin],
    functions: &FunctionSpans,
) -> Option<LineLinks> {
    if origins.iter().all(|origin| origin.line == 0) {
        return None;
    }
    let mut links: LineLinks = std::iter::once(None)
        .chain(
            origins
                .iter()
                .map(|origin| (origin.line > 0).then_some((origin.line, origin.line))),
        )
        .collect();
    for &(source, (first, last)) in functions {
        let Some(body) = links.get_mut(first..=last) else {
            continue;
        };
        if body.iter().all(Option::is_none) {
            body.fill(Some(source));
            continue;
        }
        let is_code = |line: usize| origins.get(line - 1).is_some_and(|origin| origin.code);
        if !is_code(first) {
            body[0] = Some(source);
        }
        if !is_code(last) {
            body[last - first] = Some(source);
        }
    }
    Some(links)
}

/// Each function's name and first and last line (1-based) in `text`: a
/// function starts where `start` names one and ends at its closing brace, or
/// before the next start, trimmed of trailing blank lines.
fn function_spans(text: &str, start: fn(&str) -> Option<&str>) -> Vec<(String, (usize, usize))> {
    let lines: Vec<&str> = text.lines().collect();
    let starts: Vec<(usize, &str)> = lines
        .iter()
        .enumerate()
        .filter_map(|(index, line)| start(line).map(|name| (index, name)))
        .collect();
    starts
        .iter()
        .enumerate()
        .map(|(position, &(first, name))| {
            let mut last = starts.get(position + 1).map_or(lines.len(), |next| next.0) - 1;
            if let Some(end) = (first..=last).find(|&index| lines[index] == "}") {
                last = end;
            }
            while last > first && lines[last].trim().is_empty() {
                last -= 1;
            }
            (name.to_owned(), (first + 1, last + 1))
        })
        .collect()
}

/// `int main(void) {` defines `main` (a definition starts in column 1 and is
/// not a declaration ending in `;`).
fn source_function(line: &str) -> Option<&str> {
    if line.starts_with([' ', '\t', '#', '/', '}']) || line.trim_end().ends_with(';') {
        return None;
    }
    let (head, _) = line.split_once('(')?;
    let name = head.rsplit([' ', '*']).next()?;
    (!name.is_empty()
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'))
    .then_some(name)
}

/// `define i32 @main() {`
fn llvm_function(line: &str) -> Option<&str> {
    line.strip_prefix("define ")?
        .split_once('@')?
        .1
        .split('(')
        .next()
}

/// A token line such as `<input>:12:5: keyword for` comes from line 12; a
/// token from a header comes from no line of the source.
fn token_line(line: &str) -> Option<usize> {
    let mut fields = line.splitn(4, ':');
    (fields.next()? == crate::INPUT_NAME)
        .then(|| fields.next()?.parse().ok())
        .flatten()
}

/// `block-item: for @12:5` comes from line 12.
fn syntax_line(line: &str) -> Option<usize> {
    let (_, location) = line.rsplit_once(" @")?;
    location.split(':').next()?.parse().ok()
}

/// What `-O2` changed in `stage`, comparing the `-O0` and `-O2`
/// compilations of one program: a sentence per measure that changed.
pub fn optimizer_changes(
    stage: Stage,
    plain: &Compilation,
    optimized: &Compilation,
) -> Vec<String> {
    let (Some(before), Some(after)) = (plain.output(stage), optimized.output(stage)) else {
        return Vec::new();
    };
    let before = Census::of(stage, before);
    let after = Census::of(stage, after);
    let mut changes = Vec::new();
    let mut compare = |what: &str, before: usize, after: usize, why: &str| {
        // The reason explains a saving, not a cost.
        let why = if after < before { why } else { "" };
        if before != after {
            changes.push(format!("{what}: {before} at -O0, {after} at -O2.{why}"));
        }
    };
    let unit = if matches!(stage, Stage::Asm | Stage::MachineCode) {
        "Machine instructions"
    } else {
        "Instructions"
    };
    compare(unit, before.instructions, after.instructions, "");
    if stage == Stage::MachineCode {
        compare("Bytes of code", plain.code_bytes, optimized.code_bytes, "");
    }
    compare(
        "Basic blocks",
        before.blocks,
        after.blocks,
        " Fewer blocks means simpler control flow.",
    );
    compare(
        "Memory loads and stores",
        before.memory,
        after.memory,
        " Values that stay out of memory can live in registers.",
    );
    compare(
        "Stack slots",
        before.slots,
        after.slots,
        " Each one is memory reserved in the function's stack frame.",
    );
    // A call to a function the program defines that disappeared was inlined.
    let defined: Vec<&str> = plain
        .functions
        .iter()
        .map(|function| function.name.as_str())
        .collect();
    for callee in &before.callees {
        if !after.callees.contains(callee) && defined.contains(&callee.as_str()) {
            changes.push(format!(
                "{callee} is no longer called: the optimizer inlined it, copying its body into \
                 the caller, where it could be simplified further."
            ));
        }
    }
    if changes.is_empty() && stage.phase() != "Front end" {
        changes.push(
            "The optimizer found nothing to improve here: this output is the same size at both \
             levels."
                .to_owned(),
        );
    }
    changes
}

/// Counts of what one stage's output holds.
#[derive(Default)]
struct Census {
    instructions: usize,
    blocks:       usize,
    memory:       usize,
    slots:        usize,
    callees:      Vec<String>,
}

impl Census {
    fn of(stage: Stage, text: &str) -> Self {
        let mut census = Self::default();
        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with([';', '#']) {
                continue;
            }
            let instruction = match stage {
                | Stage::Ir | Stage::IrAbi => {
                    if trimmed.starts_with("block") && trimmed.ends_with(':') {
                        census.blocks += 1;
                        false
                    } else if trimmed.contains("= stack_slot") {
                        census.slots += 1;
                        false
                    } else {
                        line.starts_with("    ")
                    }
                },
                | Stage::Llvm => {
                    if !line.starts_with(' ') && trimmed.ends_with(':') {
                        census.blocks += 1;
                    }
                    if trimmed.contains("= alloca") {
                        census.slots += 1;
                    }
                    line.starts_with("  ")
                },
                | Stage::Asm =>
                    line.starts_with('\t') && !trimmed.starts_with('.') && !trimmed.ends_with(':'),
                | Stage::MachineCode => line.starts_with(' '),
                | Stage::Lines
                | Stage::PpTokens
                | Stage::Preprocessor
                | Stage::Tokens
                | Stage::SyntaxTree
                | Stage::SemanticTypes => false,
            };
            if !instruction {
                continue;
            }
            census.instructions += 1;
            let operation = trimmed
                .split_once("= ")
                .map_or(trimmed, |(_, operation)| operation);
            if ["load", "store"]
                .iter()
                .any(|memory| operation.starts_with(memory))
            {
                census.memory += 1;
            }
            if let Some((_, callee)) = operation.split_once("call ") {
                let callee = callee
                    .split_once('@')
                    .map_or(callee, |(_, name)| name)
                    .split(['(', ' '])
                    .next()
                    .unwrap_or_default();
                if !callee.is_empty() && !census.callees.iter().any(|known| known == callee) {
                    census.callees.push(callee.to_owned());
                }
            }
        }
        census
    }
}

/// Precomputed LLVM IR for a bundled lesson, by its file stem, at `-O2` when
/// `optimize`.
pub fn precomputed_llvm(stem: &str, optimize: bool) -> Option<&'static str> {
    macro_rules! lessons {
        ($($stem:literal),*) => {
            match (stem, optimize) {
                $(
                    | ($stem, false) => Some(include_str!(concat!("../pipeline/", $stem, "/llvm.ll"))),
                    | ($stem, true) => Some(include_str!(concat!("../pipeline/", $stem, "/llvm-O2.ll"))),
                )*
                | _ => None,
            }
        };
    }
    lessons!(
        "objects",
        "pointers",
        "recursion",
        "structs",
        "promotion",
        "overflow",
        "bounds",
        "indeterminate",
        "macros",
        "path"
    )
}

/// Where each line of the precomputed LLVM IR of a lesson came from, parsed
/// from the table `web/pipeline/generate.sh` writes beside it.
pub fn precomputed_llvm_lines(stem: &str, optimize: bool) -> Vec<LineOrigin> {
    macro_rules! lessons {
        ($($stem:literal),*) => {
            match (stem, optimize) {
                $(
                    | ($stem, false) => include_str!(concat!("../pipeline/", $stem, "/llvm.lines")),
                    | ($stem, true) => include_str!(concat!("../pipeline/", $stem, "/llvm-O2.lines")),
                )*
                | _ => "",
            }
        };
    }
    lessons!(
        "objects",
        "pointers",
        "recursion",
        "structs",
        "promotion",
        "overflow",
        "bounds",
        "indeterminate",
        "macros",
        "path"
    )
    .lines()
    .map(recorded_origin)
    .collect()
}

/// A line of such a table: `-`, `0`, a source line, or a source line and the
/// call it was inlined for, as `5@15`.
fn recorded_origin(entry: &str) -> LineOrigin {
    if entry == "-" {
        return LineOrigin::default();
    }
    let (line, call) = entry.split_once('@').unwrap_or((entry, "0"));
    LineOrigin {
        line: line.parse().unwrap_or(0),
        call: call.parse().unwrap_or(0),
        code: true,
    }
}

