//! The compiler pipeline view's data: what bcc produces at each stage for a
//! program, the explanation of each stage, the links between source lines and
//! output lines, why a failed compilation stopped, and what the optimizer
//! changed.
//!
//! Every stage but LLVM IR comes from bcc's real compiler, run in the
//! compiler Worker (`explorer.rs`), for the bundled lessons as for edited
//! source, so a lesson's view is exactly what the in-browser compiler makes of
//! it. The browser build has no LLVM, so the lessons carry LLVM IR
//! precomputed by the native compiler at both optimization levels
//! (`web/pipeline/`, regenerated by `web/pipeline/generate.sh`).

use serde::{
    Deserialize,
    Serialize,
};

/// bcc's output for one program, one field per stage.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Compilation {
    pub tokens:       Option<String>,
    pub syntax_tree:  Option<String>,
    pub ir:           Option<String>,
    pub ir_abi:       Option<String>,
    /// LLVM IR; only the native compiler produces it.
    pub llvm:         Option<String>,
    pub asm:          Option<String>,
    /// Offset, encoded bytes and instruction, one line per instruction.
    pub machine_code: Option<String>,
    /// The machine code's size in bytes.
    pub code_bytes:   usize,
    pub diagnostics:  Vec<CompileDiagnostic>,
    /// Which output lines each function definition became.
    pub functions:    Vec<FunctionLines>,
}

/// One of bcc's diagnostics, placed in the editor's coordinates.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompileDiagnostic {
    /// `error`, `warning` or `note`.
    pub severity: String,
    /// `front-end`, `middle-end` or `back-end`.
    pub stage:    String,
    pub message:  String,
    /// The range in the edited source, as 1-based lines and UTF-16 columns
    /// (the end column just past the range); `None` for a diagnostic with no
    /// place, or one in a header.
    pub range:    Option<SourceSpan>,
    /// The diagnostic as the command line prints it, with its source excerpt.
    pub rendered: String,
}

#[derive(Clone, Copy, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct SourceSpan {
    pub line:       usize,
    pub column:     usize,
    pub end_line:   usize,
    pub end_column: usize,
}

/// One function definition's lines (1-based, inclusive) in the source and in
/// each output. bcc's IR keeps no source locations, so the IR, assembly and
/// machine code link per function rather than per line.
#[derive(Clone, Debug, Default, Deserialize, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FunctionLines {
    pub name:         String,
    pub source:       (usize, usize),
    pub ir:           Option<(usize, usize)>,
    pub ir_abi:       Option<(usize, usize)>,
    pub asm:          Option<(usize, usize)>,
    pub machine_code: Option<(usize, usize)>,
}

impl FunctionLines {
    fn output(&self, stage: Stage) -> Option<(usize, usize)> {
        match stage {
            | Stage::Ir => self.ir,
            | Stage::IrAbi => self.ir_abi,
            | Stage::Asm => self.asm,
            | Stage::MachineCode => self.machine_code,
            | Stage::Tokens | Stage::SyntaxTree | Stage::Llvm => None,
        }
    }
}

impl Compilation {
    /// The output of `stage`.
    pub fn output(&self, stage: Stage) -> Option<&str> {
        match stage {
            | Stage::Tokens => self.tokens.as_deref(),
            | Stage::SyntaxTree => self.syntax_tree.as_deref(),
            | Stage::Ir => self.ir.as_deref(),
            | Stage::IrAbi => self.ir_abi.as_deref(),
            | Stage::Llvm => self.llvm.as_deref(),
            | Stage::Asm => self.asm.as_deref(),
            | Stage::MachineCode => self.machine_code.as_deref(),
        }
        .filter(|text| !text.trim().is_empty())
    }

    /// Why bcc stopped before the last stage, if an error stopped it.
    pub fn stop(&self) -> Option<Stop> {
        let error = self
            .diagnostics
            .iter()
            .find(|diagnostic| diagnostic.severity == "error")?;
        let at = error
            .range
            .map(|range| format!(" on line {}", range.line))
            .unwrap_or_default();
        let message = &error.message;
        let (phase, explanation) = match error.stage.as_str() {
            | "middle-end" => (
                "Middle end",
                format!(
                    "The front end accepted your program, but bcc could not lower it into its \
                     IR{at}: “{message}”. This is usually a part of C that bcc does not translate \
                     yet, not a mistake in your program, so the IR, assembly and machine code \
                     stages have nothing to show."
                ),
            ),
            | "back-end" => (
                "Back end",
                format!(
                    "The IR is complete, but bcc's own x86-64 back end cannot turn it into \
                     assembly yet: “{message}”. That is a gap in bcc, not in your program. The IR \
                     stages still show what the middle end made of it."
                ),
            ),
            | _ => (
                "Front end",
                format!(
                    "bcc found an error in your program{at}: “{message}”. The tokens and the \
                     syntax tree show how far the front end got (the parser recovers so it can \
                     report more than one error), but bcc translates only a program without \
                     errors, so the IR, assembly and machine code stages did not run. Fix the \
                     code with the red squiggle and the pipeline compiles again as you type."
                ),
            ),
        };
        Some(Stop {
            phase,
            explanation,
            line: error.range.map(|range| range.line),
        })
    }

    /// Whether `stage` should have run but an error stopped bcc first.
    pub fn stopped_before(&self, stage: Stage) -> bool {
        stage != Stage::Llvm && self.output(stage).is_none() && self.stop().is_some()
    }
}

/// Where and why a compilation stopped.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Stop {
    /// The part of the compiler that reported the error.
    pub phase:       &'static str,
    /// What happened and what it means, for programmers new to compilers.
    pub explanation: String,
    pub line:        Option<usize>,
}

/// One stage of the pipeline, in compilation order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Stage {
    Tokens,
    SyntaxTree,
    Ir,
    IrAbi,
    Llvm,
    Asm,
    MachineCode,
}

impl Stage {
    pub const ALL: [Self; 7] = [
        Self::Tokens,
        Self::SyntaxTree,
        Self::Ir,
        Self::IrAbi,
        Self::Llvm,
        Self::Asm,
        Self::MachineCode,
    ];

    pub fn key(self) -> &'static str {
        match self {
            | Self::Tokens => "tokens",
            | Self::SyntaxTree => "syntax-tree",
            | Self::Ir => "ir",
            | Self::IrAbi => "ir-abi",
            | Self::Llvm => "llvm",
            | Self::Asm => "asm",
            | Self::MachineCode => "machine-code",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            | Self::Tokens => "Tokens",
            | Self::SyntaxTree => "Syntax tree",
            | Self::Ir => "bcc IR",
            | Self::IrAbi => "ABI-lowered IR",
            | Self::Llvm => "LLVM IR",
            | Self::Asm => "x86-64 assembly",
            | Self::MachineCode => "Machine code",
        }
    }

    /// Which part of the compiler produces this stage.
    pub fn phase(self) -> &'static str {
        match self {
            | Self::Tokens | Self::SyntaxTree => "Front end",
            | Self::Ir | Self::IrAbi | Self::Llvm => "Middle end",
            | Self::Asm | Self::MachineCode => "Back end",
        }
    }

    /// The Monaco language that colours this stage's output.
    pub fn language(self) -> &'static str {
        match self {
            | Self::Tokens => "tokens",
            | Self::SyntaxTree => "syntax-tree",
            | Self::Ir | Self::IrAbi => "bcc-ir",
            | Self::Llvm => "llvm",
            | Self::Asm => "asm",
            | Self::MachineCode => "objdump",
        }
    }

    /// The command that produces this stage for `file` with the native
    /// compiler, at `-O2` when `optimize`.
    pub fn command(self, file: &str, optimize: bool) -> String {
        let level = if optimize { "-O2 " } else { "" };
        let flags = match self {
            | Self::Tokens => "--tokens",
            | Self::SyntaxTree => "--syntax-tree --syntax-locations",
            | Self::Ir => "--emit=ir",
            | Self::IrAbi => "--emit=ir-abi",
            | Self::Llvm => "--emit=llvm",
            | Self::Asm => "--emit=asm --backend=native",
            | Self::MachineCode => {
                let object = file.strip_suffix(".c").unwrap_or(file);
                return format!(
                    "bcc-rust {level}--backend=native -c -o {object}.o {file} && objdump -d \
                     {object}.o"
                );
            },
        };
        format!("bcc-rust {level}{flags} {file}")
    }

    /// A short explanation for programmers new to compilers.
    pub fn explanation(self) -> &'static str {
        match self {
            | Self::Tokens =>
                "First the compiler reads characters and groups them into tokens: keywords, \
                 identifiers, constants and punctuators. Whitespace and comments disappear, and \
                 the preprocessor expands macros and #include at this level. Every token keeps its \
                 line and column, which is how later errors can point at your source.",
            | Self::SyntaxTree =>
                "The parser checks the tokens against C's grammar and builds a tree. Precedence is \
                 decided here: in total + next * 2 the multiplication becomes a child of the \
                 addition. Semantic analysis then attaches types to every declaration and \
                 expression and checks rules the grammar cannot express.",
            | Self::Ir =>
                "bcc lowers the typed tree into its own intermediate representation. Each value \
                 (v1, v2, …) is assigned exactly once (static single assignment), control flow is \
                 explicit as basic blocks that pass values as block parameters, and variables that \
                 never have their address taken live in values rather than memory. Arrays still \
                 need memory, so they get a stack_slot.",
            | Self::IrAbi =>
                "ABI lowering rewrites functions and calls to follow the x86-64 System V calling \
                 convention: which arguments travel in registers, which in memory, and how values \
                 are returned. For programs that pass only ints and pointers, very little changes; \
                 structs and wide values are where this stage earns its keep.",
            | Self::Llvm =>
                "bcc can hand its IR to LLVM, the optimizer and code generator behind Clang and \
                 Rust. LLVM IR is also in SSA form; %names are values, @names are globals, and phi \
                 instructions merge values where control flow joins. Note how char arithmetic \
                 shows trunc and sext: the integer promotions made explicit.",
            | Self::Asm =>
                "bcc's own native back end selects x86-64 instructions for each IR operation, \
                 assigns values to registers, and lays out the stack frame. Arguments arrive in \
                 %rdi, %rsi, …; the result leaves in %eax. Lines starting with a dot are \
                 directives for the assembler, not instructions.",
            | Self::MachineCode =>
                "Finally each instruction is encoded as bytes, the only thing the CPU actually \
                 runs. The left column is the instruction's offset from the start of its function, \
                 then its encoding, both in hexadecimal. x86-64 instructions vary from 1 to 15 \
                 bytes long. Calls to other functions show zero bytes where the linker will later \
                 fill in the address.",
        }
    }

    /// How source lines are found in this stage's output, if they are.
    fn locations(self) -> Option<fn(&str) -> Option<usize>> {
        match self {
            | Self::Tokens => Some(token_line),
            | Self::SyntaxTree => Some(syntax_line),
            | _ => None,
        }
    }

    /// What `-O2` does at this stage, for the optimizer note.
    pub fn optimizer_note(self) -> &'static str {
        match self {
            | Self::Tokens | Self::SyntaxTree =>
                "The front end does the same work at every optimization level. The one difference \
                 is that -O2 defines the macro __OPTIMIZE__, as GCC and Clang do.",
            | Self::Ir =>
                "At -O2 bcc's optimizer rewrites this IR: inline copies small functions into their \
                 callers, sroa and promote move variables out of memory into values, fold and sccp \
                 compute constants at compile time, simplify-cfg merges blocks, gvn and licm \
                 remove repeated work, and dce deletes what nothing uses. It repeats them until \
                 nothing changes.",
            | Self::IrAbi =>
                "ABI lowering runs after the optimizer, so at -O2 it starts from the optimized IR.",
            | Self::Llvm =>
                "At -O2 this LLVM IR is translated from bcc's already optimized IR, so it shows \
                 bcc's optimizations, not LLVM's.",
            | Self::Asm | Self::MachineCode =>
                "The back end translates whatever IR it is given, so every instruction the \
                 optimizer removed is one the CPU never runs.",
        }
    }
}

/// How the lines of one stage's output relate to the source lines.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Links {
    /// For each output line (1-based, index 0 unused), the exact source line
    /// it came from, for stages that record locations.
    exact:     Option<Vec<Option<usize>>>,
    /// Otherwise each function's source lines and output lines, inclusive.
    functions: Vec<((usize, usize), (usize, usize))>,
}

impl Links {
    /// Output lines that came from `line` of the source.
    pub fn outputs_for(&self, line: usize) -> Vec<usize> {
        if let Some(exact) = &self.exact {
            return (0..exact.len())
                .filter(|&output| exact[output] == Some(line))
                .collect();
        }
        self.functions
            .iter()
            .filter(|(source, _)| (source.0..=source.1).contains(&line))
            .flat_map(|(_, output)| output.0..=output.1)
            .collect()
    }

    /// Source lines that `line` of the output came from.
    pub fn sources_for(&self, line: usize) -> Vec<usize> {
        if let Some(exact) = &self.exact {
            return exact.get(line).copied().flatten().into_iter().collect();
        }
        self.functions
            .iter()
            .filter(|(_, output)| (output.0..=output.1).contains(&line))
            .flat_map(|(source, _)| source.0..=source.1)
            .collect()
    }

    /// Whether lines link one to one rather than per function.
    pub fn is_exact(&self) -> bool {
        self.exact.is_some()
    }

    pub fn is_empty(&self) -> bool {
        self.exact.is_none() && self.functions.is_empty()
    }
}

/// The links between `source` and `stage`'s output in `compilation`. Tokens
/// and the syntax tree carry a location on every line. The IR, assembly and
/// machine code keep none, so the compiler's line map links them per
/// function; precomputed LLVM IR links to those functions by name.
pub fn links(stage: Stage, compilation: &Compilation, source: &str) -> Links {
    let Some(output) = compilation.output(stage) else {
        return Links::default();
    };
    if let Some(locate) = stage.locations() {
        return Links {
            exact:     Some(
                std::iter::once(None)
                    .chain(output.lines().map(locate))
                    .collect(),
            ),
            functions: Vec::new(),
        };
    }
    let functions = if stage == Stage::Llvm {
        // Without a live compilation (still loading), find the definitions in
        // the source.
        let defined: Vec<(String, (usize, usize))> = if compilation.functions.is_empty() {
            function_spans(source, source_function)
        } else {
            compilation
                .functions
                .iter()
                .map(|function| (function.name.clone(), function.source))
                .collect()
        };
        function_spans(output, llvm_function)
            .into_iter()
            .filter_map(|(name, output)| {
                defined
                    .iter()
                    .find(|(defined, _)| *defined == name)
                    .map(|(_, source)| (*source, output))
            })
            .collect()
    } else {
        compilation
            .functions
            .iter()
            .filter_map(|function| Some((function.source, function.output(stage)?)))
            .collect()
    };
    Links {
        exact: None,
        functions,
    }
}

/// Each function's name and first and last line (1-based) in `text`: a
/// function starts where `start` names one and ends at its closing brace, or
/// before the next start, trimmed of trailing blank lines.
fn function_spans(text: &str, start: fn(&str) -> Option<&str>) -> Vec<(String, (usize, usize))> {
    let lines: Vec<&str> = text.lines().collect();
    let starts: Vec<(usize, &str)> = lines
        .iter()
        .enumerate()
        .filter_map(|(index, line)| start(line).map(|name| (index, name)))
        .collect();
    starts
        .iter()
        .enumerate()
        .map(|(position, &(first, name))| {
            let mut last = starts.get(position + 1).map_or(lines.len(), |next| next.0) - 1;
            if let Some(end) = (first..=last).find(|&index| lines[index] == "}") {
                last = end;
            }
            while last > first && lines[last].trim().is_empty() {
                last -= 1;
            }
            (name.to_owned(), (first + 1, last + 1))
        })
        .collect()
}

/// `int main(void) {` defines `main` (a definition starts in column 1 and is
/// not a declaration ending in `;`).
fn source_function(line: &str) -> Option<&str> {
    if line.starts_with([' ', '\t', '#', '/', '}']) || line.trim_end().ends_with(';') {
        return None;
    }
    let (head, _) = line.split_once('(')?;
    let name = head.rsplit([' ', '*']).next()?;
    (!name.is_empty()
        && name
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_'))
    .then_some(name)
}

/// `define i32 @main() {`
fn llvm_function(line: &str) -> Option<&str> {
    line.strip_prefix("define ")?
        .split_once('@')?
        .1
        .split('(')
        .next()
}

/// A token line such as `<input>:12:5: keyword for` comes from line 12; a
/// token from a header comes from no line of the source.
fn token_line(line: &str) -> Option<usize> {
    let mut fields = line.splitn(4, ':');
    (fields.next()? == crate::INPUT_NAME)
        .then(|| fields.next()?.parse().ok())
        .flatten()
}

/// `block-item: for @12:5` comes from line 12.
fn syntax_line(line: &str) -> Option<usize> {
    let (_, location) = line.rsplit_once(" @")?;
    location.split(':').next()?.parse().ok()
}

/// What `-O2` changed in `stage`, comparing the `-O0` and `-O2`
/// compilations of one program: a sentence per measure that changed.
pub fn optimizer_changes(
    stage: Stage,
    plain: &Compilation,
    optimized: &Compilation,
) -> Vec<String> {
    let (Some(before), Some(after)) = (plain.output(stage), optimized.output(stage)) else {
        return Vec::new();
    };
    let before = Census::of(stage, before);
    let after = Census::of(stage, after);
    let mut changes = Vec::new();
    let mut compare = |what: &str, before: usize, after: usize, why: &str| {
        // The reason explains a saving, not a cost.
        let why = if after < before { why } else { "" };
        if before != after {
            changes.push(format!("{what}: {before} at -O0, {after} at -O2.{why}"));
        }
    };
    let unit = if matches!(stage, Stage::Asm | Stage::MachineCode) {
        "Machine instructions"
    } else {
        "Instructions"
    };
    compare(unit, before.instructions, after.instructions, "");
    if stage == Stage::MachineCode {
        compare("Bytes of code", plain.code_bytes, optimized.code_bytes, "");
    }
    compare(
        "Basic blocks",
        before.blocks,
        after.blocks,
        " Fewer blocks means simpler control flow.",
    );
    compare(
        "Memory loads and stores",
        before.memory,
        after.memory,
        " Values that stay out of memory can live in registers.",
    );
    compare(
        "Stack slots",
        before.slots,
        after.slots,
        " Each one is memory reserved in the function's stack frame.",
    );
    // A call to a function the program defines that disappeared was inlined.
    let defined: Vec<&str> = plain
        .functions
        .iter()
        .map(|function| function.name.as_str())
        .collect();
    for callee in &before.callees {
        if !after.callees.contains(callee) && defined.contains(&callee.as_str()) {
            changes.push(format!(
                "{callee} is no longer called: the optimizer inlined it, copying its body into \
                 the caller, where it could be simplified further."
            ));
        }
    }
    if changes.is_empty() && stage != Stage::Tokens && stage != Stage::SyntaxTree {
        changes.push(
            "The optimizer found nothing to improve here: this output is the same size at both \
             levels."
                .to_owned(),
        );
    }
    changes
}

/// Counts of what one stage's output holds.
#[derive(Default)]
struct Census {
    instructions: usize,
    blocks:       usize,
    memory:       usize,
    slots:        usize,
    callees:      Vec<String>,
}

impl Census {
    fn of(stage: Stage, text: &str) -> Self {
        let mut census = Self::default();
        for line in text.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with([';', '#']) {
                continue;
            }
            let instruction = match stage {
                | Stage::Ir | Stage::IrAbi => {
                    if trimmed.starts_with("block") && trimmed.ends_with(':') {
                        census.blocks += 1;
                        false
                    } else if trimmed.contains("= stack_slot") {
                        census.slots += 1;
                        false
                    } else {
                        line.starts_with("    ")
                    }
                },
                | Stage::Llvm => {
                    if !line.starts_with(' ') && trimmed.ends_with(':') {
                        census.blocks += 1;
                    }
                    if trimmed.contains("= alloca") {
                        census.slots += 1;
                    }
                    line.starts_with("  ")
                },
                | Stage::Asm =>
                    line.starts_with('\t') && !trimmed.starts_with('.') && !trimmed.ends_with(':'),
                | Stage::MachineCode => line.starts_with(' '),
                | Stage::Tokens | Stage::SyntaxTree => false,
            };
            if !instruction {
                continue;
            }
            census.instructions += 1;
            let operation = trimmed
                .split_once("= ")
                .map_or(trimmed, |(_, operation)| operation);
            if ["load", "store"]
                .iter()
                .any(|memory| operation.starts_with(memory))
            {
                census.memory += 1;
            }
            if let Some((_, callee)) = operation.split_once("call ") {
                let callee = callee
                    .split_once('@')
                    .map_or(callee, |(_, name)| name)
                    .split(['(', ' '])
                    .next()
                    .unwrap_or_default();
                if !callee.is_empty() && !census.callees.iter().any(|known| known == callee) {
                    census.callees.push(callee.to_owned());
                }
            }
        }
        census
    }
}

/// Precomputed LLVM IR for a bundled lesson, by its file stem, at `-O2` when
/// `optimize`.
pub fn precomputed_llvm(stem: &str, optimize: bool) -> Option<&'static str> {
    macro_rules! lessons {
        ($($stem:literal),*) => {
            match (stem, optimize) {
                $(
                    | ($stem, false) => Some(include_str!(concat!("../pipeline/", $stem, "/llvm.ll"))),
                    | ($stem, true) => Some(include_str!(concat!("../pipeline/", $stem, "/llvm-O2.ll"))),
                )*
                | _ => None,
            }
        };
    }
    lessons!(
        "objects",
        "pointers",
        "recursion",
        "promotion",
        "overflow",
        "bounds",
        "indeterminate"
    )
}

/// The source each lesson's LLVM IR was generated from, to keep them in sync.
#[cfg(test)]
pub fn precomputed_source(stem: &str) -> Option<&'static str> {
    Some(match stem {
        | "objects" => include_str!("../pipeline/objects/source.c"),
        | "pointers" => include_str!("../pipeline/pointers/source.c"),
        | "recursion" => include_str!("../pipeline/recursion/source.c"),
        | "promotion" => include_str!("../pipeline/promotion/source.c"),
        | "overflow" => include_str!("../pipeline/overflow/source.c"),
        | "bounds" => include_str!("../pipeline/bounds/source.c"),
        | "indeterminate" => include_str!("../pipeline/indeterminate/source.c"),
        | _ => return None,
    })
}

