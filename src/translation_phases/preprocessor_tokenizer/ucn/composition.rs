//! The pairs canonical composition joins, for GCC's check that an
//! identifier is in Normalization Form C.
//!
//! C23: §6.4.2.1p3, p. 54; PDF p. 67 (Normalization Form C).

/// Whether canonical composition joins `mark` to `base` directly before
/// it: whether `base` followed by `mark` spells, in Normalization Form C,
/// one precomposed character, as `a` followed by U+0300 spells `à`.
pub(super) fn composes(base: char, mark: char) -> bool {
    let key = (u64::from(base) << 32) | u64::from(mark);
    PAIRS.binary_search(&key).is_ok()
}

