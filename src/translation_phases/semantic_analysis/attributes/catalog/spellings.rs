//! The attribute spellings bundled Clang (LLVM 23.1.1) recognizes in C on
//! the x86-64 targets bcc supports: the GNU `__attribute__` spelling, the
//! `[[gnu::...]]` and `[[clang::...]]` scoped spellings and the
//! `__declspec` spelling. Clang gives most of its own attributes a
//! `clang::` scope and GCC's attributes a `gnu::` scope, so
//! `[[clang::weak]]` is unknown while `[[gnu::weak]]` is `weak`. Some names
//! exist only for one target family. The table answers `__has_attribute`
//! and `__has_c_attribute` for scoped names, and decides which spellings the
//! catalog treats as known.
//!
//! The table was read from the pinned Clang itself: every identifier-like
//! string in the `clang` binary (and every suffix of one) was queried with
//! `__has_attribute`, `__has_c_attribute(gnu::...)`,
//! `__has_c_attribute(clang::...)` and `__has_declspec_attribute` under
//! `-std=c23` for `x86_64-unknown-linux-gnu`, `x86_64-unknown-linux-musl`,
//! `x86_64-w64-windows-gnu` and `x86_64-pc-windows-msvc`. Unscoped C23
//! standard attributes are not listed; `catalog::standard` owns them.
//! Clang extension: Clang Attributes Reference.
//! <https://clang.llvm.org/docs/AttributeReference.html>
//! Clang extension: Clang Language Extensions, "`__has_attribute`".
//! <https://clang.llvm.org/docs/LanguageExtensions.html#has-attribute>
//! C23: §6.7.13.2p1-3, pp. 142-143; PDF pp. 155-156 (vendor prefixes are
//! implementation-defined).

use crate::target::Target;

/// The spellings of `name` that Clang recognizes for `target`, or `None`
/// when Clang knows no attribute of that name there.
pub(in crate::translation_phases::semantic_analysis) fn clang(
    name: &str,
    target: Target,
) -> Option<Spellings> {
    let index = CLANG
        .binary_search_by(|(entry, _)| (*entry).cmp(name))
        .ok()?;
    let spellings = Spellings(CLANG[index].1);
    let windows = matches!(target, Target::WindowsGnu | Target::WindowsMsvc);
    let available = if spellings.contains(Spellings::WINDOWS_ONLY) {
        windows
    } else if spellings.contains(Spellings::GLIBC_ONLY) {
        target == Target::LinuxGnu
    } else {
        true
    };
    available.then_some(spellings)
}

/// Whether Clang knows `name` for any target.
pub(in crate::translation_phases::semantic_analysis) fn listed(name: &str) -> bool {
    CLANG
        .binary_search_by(|(entry, _)| (*entry).cmp(name))
        .is_ok()
}

/// A set of attribute spellings.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(in crate::translation_phases::semantic_analysis) struct Spellings(u8);

impl Spellings {
    /// `[[clang::name]]`: Clang's own attributes that allow a C spelling.
    pub(in crate::translation_phases::semantic_analysis) const CLANG_SCOPE: Self =
        Self(CLANG_SCOPE);
    /// `__declspec(name)` (Microsoft extensions).
    pub(in crate::translation_phases::semantic_analysis) const DECLSPEC: Self = Self(DECLSPEC);
    const GLIBC_ONLY: Self = Self(GLIBC_ONLY);
    /// `__attribute__((name))`, which `__has_attribute` reports.
    pub(in crate::translation_phases::semantic_analysis) const GNU: Self = Self(GNU);
    /// `[[gnu::name]]`: GCC's attributes.
    pub(in crate::translation_phases::semantic_analysis) const GNU_SCOPE: Self = Self(GNU_SCOPE);
    const WINDOWS_ONLY: Self = Self(WINDOWS_ONLY);

    pub(in crate::translation_phases::semantic_analysis) const fn contains(
        self,
        other: Self,
    ) -> bool {
        self.0 & other.0 == other.0
    }
}

