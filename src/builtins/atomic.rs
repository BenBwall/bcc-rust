const fn descriptor(id: Id, spelling: &'static str, atomic: AtomicBuiltin) -> BuiltinDescriptor {
    BuiltinDescriptor {
        id,
        spelling,
        availability: Availability {
            feature: None,
            naming:  NamingPolicy::Reserved,
        },
        syntax: SyntaxForm::OrdinaryCall,
        designator: DesignatorPolicy::DirectCallOnly,
        signature: Signature {
            result:     SignatureType::Scalar(Scalar::Int),
            parameters: &[],
            prototype:  false,
            variadic:   false,
        },
        type_rule: TypeRule::Atomic,
        arguments: &[],
        arity: (
            atomic.count,
            if matches!(atomic.family, F::Sync) && atomic.count != 0 {
                usize::MAX
            } else {
                atomic.count
            },
        ),
        effects: if matches!(atomic.operation, O::AlwaysLockFree | O::IsLockFree) {
            BuiltinEffectClass::Query
        } else {
            BuiltinEffectClass::Write
        },
        operation: B::Atomic(atomic),
        library: None,
    }
}
